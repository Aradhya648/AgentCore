/** lucide 名称 → 组件。内容源与侧栏共用，缺省回落 BookOpen。 */
const MANUAL_ICONS: Record<string, LucideIcon> = {
  Activity,
  BookMarked,
  BookOpen,
  Brain,
  Compass,
  Crown,
  FolderOpen,
  Hand,
  HelpCircle,
  Layers,
  LayoutGrid,
  LifeBuoy,
  Lock,
  MessageSquare,
  Network,
  PlayCircle,
  Rocket,
  RotateCcw,
  Route,
  Settings,
  ShieldCheck,
  SlidersHorizontal,
  Swords,
  Target,
  UsersRound,
  Wrench,
};

export function resolveManualIcon(name: string): LucideIcon {
  return MANUAL_ICONS[name] ?? BookOpen;
}
